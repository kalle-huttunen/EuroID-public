/**
 * Blueprint Node Schema
 *
 * Defines the MongoDB schema for storing ReactFlow canvas nodes that represent
 * target systems (Spokes) in the identity hub architecture. Each node contains:
 * - nodeId: Unique identifier for the node (e.g., 'entra-target')
 * - nodeType: Type of target system (e.g., 'AD', 'Slack', 'HR')
 * - config: Configuration data including credentials, IPs, and field mappings
 * - policies: Role-based policies and business logic for the Brain/Hub
 */
import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { Document } from 'mongoose';

@Schema({ timestamps: true })
export class BlueprintNode extends Document {
  @Prop({ required: true, index: true })
  tenantId!: string;

  @Prop({ required: true })
  nodeId!: string; // e.g., 'entra-target'

  @Prop()
  nodeType!: string; // e.g., 'AD', 'Slack', 'HR'

  @Prop({ type: Object })
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- dynamic connector config; shape varies per connector type
  config!: any; // Stores the JSON from the Form (IPs, Passwords, Mapping)

  @Prop({ type: Array })
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- dynamic policy structure; shape varies per brain rule
  policies!: any[]; // Stores the Role & Policy logic for the Brain
}

export const BlueprintSchema = SchemaFactory.createForClass(BlueprintNode);

BlueprintSchema.index({ tenantId: 1, nodeId: 1 }, { unique: true });

/** Pipeline lifecycle status for blueprint deployment. */
export enum PipelineStatus {
  DRAFT = 'DRAFT',
  SIMULATED = 'SIMULATED',
  DEPLOYED = 'DEPLOYED',
  PAUSED = 'PAUSED',
  STOPPED = 'STOPPED',
}

/** Pause reason when pipeline is PAUSED. */
export type PauseReason = 'manual' | 'circuit_breaker' | 'health_failure';

@Schema({ _id: false })
export class PipelineConfigEmbed {
  @Prop({ enum: PipelineStatus, default: PipelineStatus.DRAFT })
  status!: PipelineStatus;

  @Prop()
  deployedAt!: Date;

  @Prop()
  deployedBy!: string;

  @Prop()
  pausedAt!: Date;

  @Prop()
  pauseReason!: PauseReason;

  @Prop({ default: 5 })
  errorThresholdPercent!: number;

  @Prop()
  lastSimulationAt!: Date;

  @Prop()
  lastSimulationRisk!: 'low' | 'medium' | 'high' | 'critical';

  /** When the canvas was last saved (saveBlueprint): an impact analysis before it is stale. */
  @Prop()
  canvasSavedAt?: Date;

  @Prop({ default: 5 })
  minSampleSizeForCircuitBreaker!: number;
}

const PipelineConfigSchemaDef = SchemaFactory.createForClass(PipelineConfigEmbed);

/**
 * Canvas Blueprint Schema
 *
 * Stores the complete ReactFlow canvas state including all nodes, edges,
 * viewport position, and connector configurations. This enables persistence
 * across page refreshes and provides a foundation for versioning (draft/active).
 *
 * Design: Singleton pattern - one active canvas per system for simplicity.
 * Future: Add versioning support with version field (draft, active, archived).
 */
@Schema({ timestamps: true })
export class CanvasBlueprint extends Document {
  @Prop({ required: true, index: true })
  tenantId!: string;

  @Prop({ required: true, default: 'draft' })
  version!: string; // 'draft' or 'active' - enables future versioning support

  @Prop({ type: Array, default: [] })
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- ReactFlow Node type has dynamic data payload
  nodes!: any[];

  @Prop({ type: Array, default: [] })
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- ReactFlow Edge type has dynamic data payload
  edges!: any[];

  @Prop({ type: Object, default: { x: 0, y: 0, zoom: 1 } })
  viewport!: { x: number; y: number; zoom: number }; // Camera position and zoom level

  @Prop({ type: Object, default: {} })
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- connector configs are dynamic per-connector type
  connectorConfigs!: Record<string, any>;

  @Prop({
    type: PipelineConfigSchemaDef,
    default: () => ({
      status: PipelineStatus.DRAFT,
      errorThresholdPercent: 5,
      minSampleSizeForCircuitBreaker: 5,
    }),
  })
  pipelineConfig!: PipelineConfigEmbed;

  /**
   * Counts the canvas saves (saveBlueprint). GET /blueprints/latest returns it and the Design
   * studio sends it back with its save: a save of an older revision is refused (409), so a second
   * admin's save never silently overwrites the first one's. Unset (a canvas saved before it
   * existed) reads as 0.
   */
  @Prop()
  canvasRevision?: number;

  // Timestamp fields (auto-generated by { timestamps: true })
  createdAt!: Date;
  updatedAt!: Date;
}

export const CanvasBlueprintSchema = SchemaFactory.createForClass(CanvasBlueprint);
