/**
 * Rego Compiler Service
 *
 * Translates EuroID Policy documents (MongoDB schema) into Rego rules
 * that OPA can evaluate. Each policy becomes a Rego rule that contributes
 * to the overall decision.
 *
 * The compiled bundle is pushed to OPA via the OPA Client Service.
 */
import { Injectable, Logger } from '@nestjs/common';
import type { Policy } from '../schemas/policy.schema';

/**
 * Operator-to-Rego expression mapping.
 *
 * Each operator produces a Rego expression comparing `userVal` against `condVal`.
 * `userVal` is the resolved user field, `condVal` is the condition's expected value.
 */
/* eslint-disable no-restricted-syntax -- JSON.stringify here generates Rego source code, not log output */
const OPERATOR_MAP: Record<string, (userExpr: string, condVal: string) => string> = {
  equals: (u, v) => `${u} == ${JSON.stringify(v)}`,
  not_equals: (u, v) => `${u} != ${JSON.stringify(v)}`,
  contains: (u, v) => `contains(${u}, ${JSON.stringify(v)})`,
  starts_with: (u, v) => `startswith(${u}, ${JSON.stringify(v)})`,
  ends_with: (u, v) => `endswith(${u}, ${JSON.stringify(v)})`,
  in: (u, v) => {
    const values = v.split(',').map((s) => s.trim());
    const set = `{${values.map((val) => JSON.stringify(val)).join(', ')}}`;
    return `${set}[${u}]`;
  },
  not_in: (u, v) => {
    const values = v.split(',').map((s) => s.trim());
    const set = `{${values.map((val) => JSON.stringify(val)).join(', ')}}`;
    return `not ${set}[${u}]`;
  },
  regex: (u, v) => `regex.match(${JSON.stringify(v)}, ${u})`,
  greater_than: (u, v) => `to_number(${u}) > ${Number(v)}`,
  less_than: (u, v) => `to_number(${u}) < ${Number(v)}`,
  is_empty: (u) => `${u} == ""`,
  is_not_empty: (u) => `${u} != ""`,
};
/* eslint-enable no-restricted-syntax */

/** Maps frontend action types to canonical types. */
const ACTION_TYPE_MAP: Record<string, string> = {
  assign_group: 'group',
  assign_license: 'license',
  assign_role: 'role',
  set_attribute: 'attribute',
  enable_mfa: 'mfa',
  conditional_access: 'conditional_access',
  notification: 'notification',
  trigger_workflow: 'workflow',
};

@Injectable()
export class RegoCompilerService {
  private readonly logger = new Logger(RegoCompilerService.name);

  /**
   * Compile an array of EuroID policies into a single Rego module.
   * The module exports `evaluate` which returns operations for a given user input.
   */
  compile(policies: Policy[], tenantId: string): string {
    const policyRules = policies
      .filter((p) => p.status === 'active')
      .sort((a, b) => (b.priority ?? 0) - (a.priority ?? 0))
      .map((p) => this.compileSinglePolicy(p))
      .join('\n\n');

    return `# Auto-generated by EuroID Rego Compiler
# Tenant: ${tenantId}
# Generated: ${new Date().toISOString()}
# Policies: ${policies.length}

package euroid.policy.evaluate

import rego.v1

default operations := []

# Collect operations from all matching policies
operations := result if {
  result := [op |
    some policy_ops in matched_operations
    some op in policy_ops
  ]
}

${policyRules}
`;
  }

  /**
   * Compile a single policy into a Rego rule that contributes to matched_operations.
   */
  private compileSinglePolicy(policy: Policy): string {
    const safeName = this.sanitizeName(policy.name);
    // eslint-disable-next-line @typescript-eslint/no-explicit-any -- Mongoose document has _id but Policy class type doesn't declare it
    const policyId = (policy as any)._id?.toString() ?? safeName;

    const conditionLines = this.compileConditionGroups(policy.conditionGroups ?? []);
    const actionLines = this.compileActions(policy.actions ?? [], policyId);

    if (conditionLines.length === 0) {
      return `# Policy: ${policy.name} (no conditions — always matches)
matched_operations contains ops if {
  ops := [${actionLines.join(', ')}]
}`;
    }

    return `# Policy: ${policy.name} (priority: ${policy.priority ?? 0})
matched_operations contains ops if {
${conditionLines.map((l) => `  ${l}`).join('\n')}
  ops := [${actionLines.join(', ')}]
}`;
  }

  /**
   * Compile condition groups into Rego expressions.
   * User must match ALL groups. Within each group, conditions use the group's join (AND/OR).
   */
  private compileConditionGroups(groups: Policy['conditionGroups']): string[] {
    if (!groups || groups.length === 0) return [];

    const lines: string[] = [];

    for (const group of groups) {
      if (!group.conditions || group.conditions.length === 0) continue;

      const join = (group.join ?? 'AND').toUpperCase();
      const condExprs = group.conditions
        .map((c) => this.compileCondition(c))
        .filter((expr): expr is string => expr !== null);

      if (condExprs.length === 0) continue;

      if (join === 'OR') {
        // OR: at least one condition must be true
        lines.push(`# Group: ${group.id || 'unnamed'} (OR)`);
        lines.push(`any([${condExprs.map((e) => `(${e})`).join(', ')}])`);
      } else {
        // AND: all conditions must be true
        lines.push(`# Group: ${group.id || 'unnamed'} (AND)`);
        for (const expr of condExprs) {
          lines.push(expr);
        }
      }
    }

    return lines;
  }

  /**
   * Compile a single condition into a Rego expression.
   */
  private compileCondition(condition: {
    field: string;
    operator: string;
    value?: string | string[];
  }): string | null {
    const { field, operator, value } = condition;
    const condValue = Array.isArray(value) ? value.join(',') : (value ?? '');

    // Resolve user field expression
    const userExpr = this.resolveFieldExpr(field);

    const mapper = OPERATOR_MAP[operator];
    if (!mapper) {
      this.logger.warn(`Unknown operator "${operator}" in condition for field "${field}"`);
      return null;
    }

    return mapper(userExpr, condValue);
  }

  /**
   * Map a field name to a Rego input expression.
   * Handles customAttributes.* dotting.
   */
  private resolveFieldExpr(field: string): string {
    if (field.startsWith('customAttributes.')) {
      const key = field.slice('customAttributes.'.length);
      return `input.user.customAttributes["${key}"]`;
    }
    return `input.user.${field}`;
  }

  /**
   * Compile policy actions into Rego object literals.
   */
  private compileActions(actions: Policy['actions'], policyId: string): string[] {
    if (!actions || actions.length === 0) return [];

    return actions.map((action) => {
      const type = ACTION_TYPE_MAP[action.type] ?? action.type;
      const target = action.target ?? '';
      const targetId =
        action.params?.['targetId'] ?? action.params?.['groupName'] ?? action.label ?? '';

      const obj: Record<string, unknown> = {
        type,
        action: 'add',
        target,
        targetId: String(targetId),
        sourcePolicy: policyId,
      };

      if (action.params) {
        obj.params = action.params;
      }

      if (action.timeConstraint) {
        obj.timeConstraint = action.timeConstraint;
      }

      return JSON.stringify(obj);
    });
  }

  /**
   * Sanitize a policy name for use as a Rego identifier.
   */
  private sanitizeName(name: string): string {
    return name
      .toLowerCase()
      .replace(/[^a-z0-9_]/g, '_')
      .replace(/_{2,}/g, '_')
      .replace(/^_|_$/g, '')
      .slice(0, 64);
  }
}
